export function getProductDetails(productId?: string): ProductDetailsData {
  if (!productId) return DEFAULT_PRODUCT_DETAILS;

  // Search through all sections to see if product exists
  const allProducts = CATALOGUE_SECTIONS.flatMap((s) => s.products);
  const found = allProducts.find((p) => p.id === productId);

  if (!found) return DEFAULT_PRODUCT_DETAILS;

  return {
    ...DEFAULT_PRODUCT_DETAILS,
    id: found.id,
    name: found.name,
    category: found.category || DEFAULT_PRODUCT_DETAILS.category,
    supplier: found.supplier || DEFAULT_PRODUCT_DETAILS.supplier,
    price: found.price,
    currency: found.currency || DEFAULT_PRODUCT_DETAILS.currency,
    inStock: found.inStock ?? true,
    images: found.imageUrl
      ? [found.imageUrl, ...DEFAULT_PRODUCT_IMAGES.slice(1)]
      : DEFAULT_PRODUCT_IMAGES,
  };
}
